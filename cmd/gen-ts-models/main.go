// Command gen-ts-models writes frontend/src/models.ts: TypeScript interfaces
// for the Go types the configurator frontend exchanges with the plugin, in
// namespaces named after their Go package (pkg.Profile, profilestore.Status).
//
// Types only: values cross the SkyScript bridge as plain JSON, so there is
// nothing to construct at runtime.
//
//	go run ./cmd/gen-ts-models            # regenerate
//	go test ./cmd/gen-ts-models           # fails if models.ts is stale
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/x-z7a/zoal-honeycomb/pkg"
	"github.com/x-z7a/zoal-honeycomb/pkg/profilestore"
)

// roots are the types the frontend uses directly; everything they reference
// is generated too.
var roots = []any{
	pkg.Profile{},
	profilestore.Status{},
}

const outputPath = "frontend/src/models.ts"

func main() {
	out := flag.String("o", outputPath, "output file, relative to the module root")
	flag.Parse()

	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	target := filepath.Join(root, *out)
	if err := os.WriteFile(target, []byte(Generate()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", target)
}

// Generate returns the contents of models.ts.
func Generate() string {
	g := &generator{seen: map[reflect.Type]bool{}}
	for _, r := range roots {
		g.visit(reflect.TypeOf(r))
	}

	// Group by namespace, keeping dependency order (leaves first) inside each.
	var namespaces []string
	byNamespace := map[string][]reflect.Type{}
	for _, t := range g.order {
		ns := namespaceOf(t)
		if _, ok := byNamespace[ns]; !ok {
			namespaces = append(namespaces, ns)
		}
		byNamespace[ns] = append(byNamespace[ns], t)
	}
	sort.Strings(namespaces)

	var b strings.Builder
	b.WriteString("// Code generated by cmd/gen-ts-models; DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go run ./cmd/gen-ts-models\n\n")
	for _, ns := range namespaces {
		fmt.Fprintf(&b, "export namespace %s {\n", ns)
		for _, t := range byNamespace[ns] {
			writeInterface(&b, t, ns)
		}
		b.WriteString("}\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

type generator struct {
	seen  map[reflect.Type]bool
	order []reflect.Type
}

// visit records every struct reachable from t, dependencies before dependents.
func (g *generator) visit(t reflect.Type) {
	t = elem(t)
	switch t.Kind() {
	case reflect.Slice, reflect.Array, reflect.Map:
		g.visit(t.Elem())
		return
	}
	if t.Kind() != reflect.Struct || g.seen[t] {
		return
	}
	g.seen[t] = true
	for _, f := range fields(t) {
		g.visit(f.typ)
	}
	g.order = append(g.order, t)
}

type field struct {
	name     string
	typ      reflect.Type
	optional bool
}

// fields lists t's JSON fields the way encoding/json sees them: json:"-" and
// unexported fields are dropped and untagged embedded structs are flattened.
func fields(t reflect.Type) []field {
	var out []field
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Anonymous && name == "" && elem(f.Type).Kind() == reflect.Struct {
			out = append(out, fields(elem(f.Type))...)
			continue
		}
		if !f.IsExported() {
			continue
		}
		if name == "" {
			name = f.Name
		}
		out = append(out, field{
			name:     name,
			typ:      f.Type,
			optional: strings.Contains(opts, "omitempty") || f.Type.Kind() == reflect.Pointer,
		})
	}
	return out
}

func writeInterface(b *strings.Builder, t reflect.Type, ns string) {
	fmt.Fprintf(b, "\texport interface %s {\n", t.Name())
	for _, f := range fields(t) {
		opt := ""
		if f.optional {
			opt = "?"
		}
		fmt.Fprintf(b, "\t\t%s%s: %s;\n", f.name, opt, tsType(f.typ, ns))
	}
	b.WriteString("\t}\n")
}

func tsType(t reflect.Type, ns string) string {
	t = elem(t)
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string" // encoding/json writes []byte as base64
		}
		return tsType(t.Elem(), ns) + "[]"
	case reflect.Map:
		return fmt.Sprintf("Record<%s, %s>", tsType(t.Key(), ns), tsType(t.Elem(), ns))
	case reflect.Struct:
		return className(t, ns)
	default:
		return "any"
	}
}

func className(t reflect.Type, ns string) string {
	if other := namespaceOf(t); other != ns {
		return other + "." + t.Name()
	}
	return t.Name()
}

func namespaceOf(t reflect.Type) string {
	return filepath.Base(t.PkgPath())
}

func elem(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return t
}

// moduleRoot walks up from the working directory to the folder with go.mod,
// so the generator works from the repo root, from go generate, and from tests.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", dir)
		}
		dir = parent
	}
}
